// Builds the self-contained monitor page.
// In: an authenticated GET for the base monitor route.
// Out: HTML that polls status and lets the user inspect one month's log.
var html = [
  '<!doctype html>',
  '<html lang="en">',
  '<head><meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width,initial-scale=1">',
  '<title>Report run monitor</title>',
  '<style>',
  'body{font:15px system-ui,sans-serif;margin:2rem;max-width:1100px}',
  'h1{font-size:1.5rem}button,select,input{font:inherit;padding:.4rem}',
  'pre{background:#f4f4f4;padding:1rem;overflow:auto}',
  '.error{color:#a00}label{margin-right:.5rem}',
  '</style></head>',
  '<body><h1>Report run monitor</h1>',
  '<p>Live status refreshes every 10 seconds. STUCK means no checkpoint',
  ' arrived for 30 minutes while a run was active.</p>',
  '<pre id="status">Loading status...</pre>',
  '<h2>Run log history</h2>',
  '<form id="historyForm">',
  '<label>Flow <select id="flow">',
  '<option value="sih-hull">SIH report daily</option>',
  '<option value="rpt-hull">Shift report</option>',
  '<option value="pbi-report">PBI report build</option>',
  '</select></label>',
  '<label>Month <input id="month" type="month" required></label>',
  '<button type="submit">Load history</button></form>',
  '<p id="historyError" class="error"></p>',
  '<pre id="history">Choose a flow and month.</pre>',
  '<script>',
  '(function(){',
  'var key=new URLSearchParams(location.search).get("key")||"";',
  'var base=location.pathname.replace(/\\/(status|history)\\/?$/,"");',
  'function url(view,params){',
  '  var out=base+"/"+view+"?key="+encodeURIComponent(key);',
  '  Object.keys(params||{}).forEach(function(name){',
  '    out+="&"+encodeURIComponent(name)+"=";',
  '    out+=encodeURIComponent(params[name]);',
  '  });',
  '  return out;',
  '}',
  'function refresh(){',
  '  fetch(url("status")).then(function(response){',
  '    if(!response.ok){throw new Error("HTTP "+response.status);}',
  '    return response.json();',
  '  }).then(function(data){',
  '    document.getElementById("status").textContent=',
  '      JSON.stringify(data,null,2);',
  '  }).catch(function(error){',
  '    document.getElementById("status").textContent=',
  '      "Status request failed: "+error.message;',
  '  });',
  '}',
  'document.getElementById("month").value=',
  '  new Date().toISOString().slice(0,7);',
  'document.getElementById("historyForm").addEventListener("submit",',
  '  function(event){',
  '    event.preventDefault();',
  '    var params={',
  '      flow:document.getElementById("flow").value,',
  '      month:document.getElementById("month").value',
  '    };',
  '    document.getElementById("historyError").textContent="";',
  '    fetch(url("history",params)).then(function(response){',
  '      return response.json().then(function(data){',
  '        if(!response.ok){throw new Error(data.error||response.status);}',
  '        return data;',
  '      });',
  '    }).then(function(data){',
  '      document.getElementById("history").textContent=',
  '        JSON.stringify(data,null,2);',
  '    }).catch(function(error){',
  '      document.getElementById("historyError").textContent=',
  '        "History request failed: "+error.message;',
  '    });',
  '  });',
  'refresh();setInterval(refresh,10000);',
  '})();',
  '</script></body></html>'
].join('\n');

msg.statusCode = 200;
msg.headers = {
  'content-type': 'text/html; charset=utf-8',
  'cache-control': 'no-store'
};
msg.payload = html;
return msg;
