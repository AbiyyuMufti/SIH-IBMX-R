// Builds the self-contained monitor page.
// In: an authenticated GET for the base monitor route.
// Out: HTML that polls status and lets the user inspect one month's log.

// Set once after the import: the access key of "Post backfill command".
// Filled: the page uses it and hides the key field. Empty: type it in the
// page. Anyone who can open this page can then queue a backfill.
var COMMAND_KEY = '';
// The key goes into the page script as a JSON string (no markup in it).
var presetKey = JSON.stringify(COMMAND_KEY).replace(/</g, '\\u003c');

var html = [
  '<!doctype html>',
  '<html lang="en">',
  '<head><meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width,initial-scale=1">',
  '<title>Report run monitor</title>',
  '<style>',
  'body{font:15px system-ui,sans-serif;margin:2rem;max-width:1100px}',
  'h1{font-size:1.5rem}button,select,input{font:inherit;padding:.4rem}',
  'pre{background:#f4f4f4;padding:1rem;overflow:auto}',
  '.error{color:#a00}label{margin-right:.5rem}',
  '</style></head>',
  '<body><h1>Report run monitor</h1>',
  '<p>Live status refreshes every 10 seconds. STUCK means no checkpoint',
  ' arrived for 30 minutes while a run was active.</p>',
  '<pre id="status">Loading status...</pre>',
  '<h2>Run log history</h2>',
  '<form id="historyForm">',
  '<label>Flow <select id="flow">',
  '<option value="sih-hull">SIH report daily</option>',
  '<option value="rpt-hull">Shift report</option>',
  '<option value="pbi-report">PBI report build</option>',
  '<option value="run-monitor">Monitor command log</option>',
  '</select></label>',
  '<label>Month <input id="month" type="month" required></label>',
  '<button type="submit">Load history</button></form>',
  '<p id="historyError" class="error"></p>',
  '<pre id="history">Choose a flow and month.</pre>',
  '<h2>Backfill command</h2>',
  '<p>The POST endpoint has its own key. Caps: 31 days or 12 months.',
  ' Force may run a second backfill concurrently.</p>',
  '<form id="commandForm">',
  '<label>Flow <select id="commandFlow">',
  '<option value="sih-hull">SIH report daily</option>',
  '<option value="rpt-hull">Shift report</option>',
  '<option value="pbi-report">PBI report build</option>',
  '</select></label>',
  '<div id="dateFields">',
  '<label>Start <input id="start" type="date"></label>',
  '<label>End <input id="end" type="date"></label></div>',
  '<div id="monthFields" hidden>',
  '<label>From <input id="fromMonth" type="month"></label>',
  '<label>To <input id="toMonth" type="month"></label></div>',
  '<div id="keyRow">',
  '<label>Command key <input id="commandKey" type="text" size="50"',
  ' autocomplete="off"></label>',
  '<p>Paste the key of "Post backfill command" (the text after key=;',
  ' a pasted URL also works), or set COMMAND_KEY in node 2.1.</p></div>',
  '<label><input id="force" type="checkbox">Force if busy</label>',
  '<button type="submit">Queue backfill</button></form>',
  '<p id="commandError" class="error"></p>',
  '<pre id="commandResult">No command sent.</pre>',
  '<script>',
  '(function(){',
  'var presetKey=' + presetKey + ';',
  'document.getElementById("keyRow").hidden=presetKey!=="";',
  'var key=new URLSearchParams(location.search).get("key")||"";',
  'var base=location.pathname.replace(/\\/+$/,"");',
  'function url(view,params){',
  '  var out=base+"?view="+encodeURIComponent(view);',
  '  out+="&key="+encodeURIComponent(key);',
  '  Object.keys(params||{}).forEach(function(name){',
  '    out+="&"+encodeURIComponent(name)+"=";',
  '    out+=encodeURIComponent(params[name]);',
  '  });',
  '  return out;',
  '}',
  'function refresh(){',
  '  fetch(url("status")).then(function(response){',
  '    if(!response.ok){throw new Error("HTTP "+response.status);}',
  '    return response.json();',
  '  }).then(function(data){',
  '    document.getElementById("status").textContent=',
  '      JSON.stringify(data,null,2);',
  '  }).catch(function(error){',
  '    document.getElementById("status").textContent=',
  '      "Status request failed: "+error.message;',
  '  });',
  '}',
  'function plainKey(text){',
  '  var found=/[?&]key=([^&\s]+)/.exec(text);',
  '  return (found?found[1]:text).trim();',
  '}',
  'function answer(response){',
  '  return response.text().then(function(text){',
  '    var data;',
  '    try{data=JSON.parse(text);}catch(e){',
  '      throw new Error("HTTP "+response.status+" "+text.slice(0,120));',
  '    }',
  '    if(!response.ok){',
  '      throw new Error(data.error||"HTTP "+response.status);',
  '    }',
  '    return data;',
  '  });',
  '}',
  'function updateCommandFields(){',
  '  var pbi=document.getElementById("commandFlow").value==="pbi-report";',
  '  document.getElementById("dateFields").hidden=pbi;',
  '  document.getElementById("monthFields").hidden=!pbi;',
  '}',
  'document.getElementById("month").value=',
  '  new Date().toISOString().slice(0,7);',
  'document.getElementById("historyForm").addEventListener("submit",',
  '  function(event){',
  '    event.preventDefault();',
  '    var params={',
  '      flow:document.getElementById("flow").value,',
  '      month:document.getElementById("month").value',
  '    };',
  '    document.getElementById("historyError").textContent="";',
  '    fetch(url("history",params)).then(function(response){',
  '      return response.json().then(function(data){',
  '        if(!response.ok){throw new Error(data.error||response.status);}',
  '        return data;',
  '      });',
  '    }).then(function(data){',
  '      document.getElementById("history").textContent=',
  '        JSON.stringify(data,null,2);',
  '    }).catch(function(error){',
  '      document.getElementById("historyError").textContent=',
  '        "History request failed: "+error.message;',
  '    });',
  '  });',
  'document.getElementById("commandFlow").addEventListener("change",',
  '  updateCommandFields);',
  'updateCommandFields();',
  'document.getElementById("commandForm").addEventListener("submit",',
  '  function(event){',
  '    event.preventDefault();',
  '    var flow=document.getElementById("commandFlow").value;',
  '    var payload={',
  '      flow:flow,',
  '      force:document.getElementById("force").checked',
  '    };',
  '    if(flow==="pbi-report"){',
  '      payload.from=document.getElementById("fromMonth").value;',
  '      payload.to=document.getElementById("toMonth").value;',
  '    }else{',
  '      payload.start=document.getElementById("start").value;',
  '      payload.end=document.getElementById("end").value;',
  '    }',
  '    var typed=document.getElementById("commandKey").value;',
  '    var commandKey=presetKey||plainKey(typed);',
  '    if(!commandKey){',
  '      document.getElementById("commandError").textContent=',
  '        "Command key missing: type it or set COMMAND_KEY in node 2.1.";',
  '      return;',
  '    }',
  '    var commandUrl=base+"/command?key="+encodeURIComponent(commandKey);',
  '    document.getElementById("commandError").textContent="";',
  '    fetch(commandUrl,{',
  '      method:"POST",',
  '      headers:{"Content-Type":"application/json"},',
  '      body:JSON.stringify(payload)',
  '    }).then(answer).then(function(data){',
  '      document.getElementById("commandResult").textContent=',
  '        JSON.stringify(data,null,2);',
  '    }).catch(function(error){',
  '      document.getElementById("commandError").textContent=',
  '        "Command failed: "+error.message;',
  '    });',
  '  });',
  'refresh();setInterval(refresh,10000);',
  '})();',
  '</script></body></html>'
].join('\n');

msg.statusCode = 200;
msg.headers = {
  'content-type': 'text/html; charset=utf-8',
  'cache-control': 'no-store'
};
msg.payload = html;
return msg;
