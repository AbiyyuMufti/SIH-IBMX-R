// Writes docs/powerbi-data-map.md from the saved draw.io file: one section
// per table sheet (1 to 6) with a row per Power BI column, our matching
// column and the difference. Reads the saved file, because it is edited
// by hand and build-drawio.js no longer owns it.
// Usage: node scripts/export-drawio-summary.js [drawio file] [output file]
import { readFileSync, writeFileSync } from 'node:fs';

const file = process.argv[2] ?? 'diagrams/powerbi-data-map.drawio';
const out = process.argv[3] ?? 'docs/powerbi-data-map.md';
// Column x of the table sheets (see "Columns on a table sheet").
const X_PBI = 40;
const X_OURS = 380;
const X_DIFF = 700;
const X_SOURCE = 710;
// Cells right of this are the flow chart, not the column table.
const X_FLOW = 1340;
const FIRST_ROW_Y = 200;

// The value is HTML inside XML: decode, drop the tags, decode again.
const decode = (s) =>
  s
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#([0-9]+);/g, (m, n) => String.fromCharCode(n))
    .replace(/&amp;/g, '&');
const text = (s) =>
  decode(decode(s.replace(/&#xa;/g, ' ')).replace(/<[^>]+>/g, ' '))
    .replace(/&nbsp;/g, ' ')
    .replace(/[ \t\r\n]+/g, ' ')
    .trim();
const cell = (s) => (s || '').replace(/\|/g, '\\|');

const xml = readFileSync(file, 'utf8');
const pages = [...xml.matchAll(/<diagram name="([^"]*)"[\s\S]*?<\/diagram>/g)];
const lines = [
  '# Power BI data map (text summary)',
  '',
  'Generated by `node scripts/export-drawio-summary.js` from',
  '`diagrams/powerbi-data-map.drawio`. Do not edit by hand; see',
  '[powerbi-diagrams.md](powerbi-diagrams.md).',
];

for (const page of pages) {
  const name = text(page[1]);
  if (!/^[1-6] /.test(name)) {
    continue;
  }
  const cells = [];
  for (const c of page[0].matchAll(
    /<mxCell id="[^"]+"([^>]*?)>\s*<mxGeometry([^>]*?)\/?>/g,
  )) {
    const v = (c[1].match(/ value="([^"]*)"/) || [])[1];
    const num = (k) =>
      Number((c[2].match(new RegExp(` ${k}="([-0-9.]+)"`)) || [])[1]);
    if (v && !c[1].includes('edge="1"') && num('x') < X_FLOW) {
      cells.push({ x: num('x'), y: num('y'), w: num('width'), t: text(v) });
    }
  }
  const title = cells.find((c) => c.y < 40);
  const intro = cells.find((c) => c.x === X_PBI && c.y > 40 && c.y < 100);
  lines.push('', `## ${name}`, '');
  lines.push(`${title ? title.t : ''}. ${intro ? intro.t : ''}`.trim(), '');
  // A row starts at a Power BI column cell; its example is the next cell.
  const anchors = cells
    .filter((c) => c.x === X_PBI && c.y >= FIRST_ROW_Y && !c.t.startsWith('e.g.'))
    .sort((a, b) => a.y - b.y);
  lines.push('| Power BI column | Example | Our column | Our example | Difference | SIH source |');
  lines.push('|---|---|---|---|---|---|');
  anchors.forEach((a, i) => {
    const end = i + 1 < anchors.length ? anchors[i + 1].y : Infinity;
    const inRow = cells.filter((c) => c.y >= a.y && c.y < end);
    const at = (x, example) =>
      inRow.find((c) => c.x === x && c.t.startsWith('e.g.') === example);
    const get = (c) => cell(c ? c.t : '');
    lines.push(
      `| ${get(a)} | ${get(at(X_PBI, true))} | ${get(at(X_OURS, false))} ` +
        `| ${get(at(X_OURS, true))} | ${get(at(X_DIFF, false))} ` +
        `| ${get(inRow.find((c) => c.x === X_SOURCE))} |`,
    );
  });
}

writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${out}`);
